import re

# Единицы измерения, которые вырезаются из названий при загрузке.
# Если появятся новые (например, "уп", "пач", "мг") — просто добавь сюда.
UNIT_CLEANUP_PATTERN = re.compile(
    r'\s*\((шт|кг|л|л/шт|мл|гр|уп|пач)\)\s*$',
    re.IGNORECASE,
)


def clean_item_name(name: str) -> str:
    """Убирает единицу измерения в скобках в конце названия.

    Примеры:
        "Молоко 3.2% (л)"  -> "Молоко 3.2%"
        "Стакан 350 (шт)"  -> "Стакан 350"
        "Без скобок"       -> "Без скобок"
    """
    return UNIT_CLEANUP_PATTERN.sub('', name).strip()